<#
.SYNOPSIS
    Updates CHANGELOG.md for Azure Resource Manager SDK packages.

.DESCRIPTION
    For a single package, reads its project name and release version, determines
    the service directory, and calls Gen-Mgmt-Changelog.ps1 with its exact API listing.
    For a PR batch, processes directly changed management packages in child processes
    and exports generated changelogs and a patch as CI artifacts.

.PARAMETER PackagePath
    Absolute path to the root folder of the local SDK package.

.PARAMETER SdkRepoPath
    Absolute path to the root folder of the local SDK repository.

.PARAMETER PackageInfoDirectory
    Directory containing PR package metadata JSON files. Missing metadata is valid.

.PARAMETER OutputDirectory
    Directory in which to collect batch changelogs and changelog.patch.

.EXAMPLE
    .\Update-MgmtChangelog.ps1 `
        -PackagePath "C:\repos\azure-sdk-for-net\sdk\apicenter\Azure.ResourceManager.ApiCenter" `
        -SdkRepoPath "C:\repos\azure-sdk-for-net"
#>

[CmdletBinding(DefaultParameterSetName = 'Package')]
param(
    [Parameter(Mandatory = $true, ParameterSetName = 'Package')]
    [ValidateScript({ Test-Path $_ -PathType Container })]
    [string]$PackagePath,

    [Parameter(Mandatory = $true)]
    [ValidateScript({ Test-Path $_ -PathType Container })]
    [string]$SdkRepoPath,

    [Parameter(Mandatory = $true, ParameterSetName = 'Batch')]
    [string]$PackageInfoDirectory,

    [Parameter(Mandatory = $true, ParameterSetName = 'Batch')]
    [string]$OutputDirectory
)

$ErrorActionPreference = "Stop"
$PSNativeCommandUseErrorActionPreference = $true

if ($PSCmdlet.ParameterSetName -eq 'Batch') {
    # Collect native failures explicitly so one failed child does not stop the batch.
    $PSNativeCommandUseErrorActionPreference = $false
    $sdkRepoPath = (Resolve-Path $SdkRepoPath).Path
    $outputDirectory = [IO.Path]::GetFullPath($OutputDirectory)
    New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
    'Generated by the AutoPR changelog job. These CHANGELOG.md files and changelog.patch are CI artifacts; this job does not commit them to the AutoPR.' |
        Set-Content (Join-Path $outputDirectory 'README.txt')

    # No matching packages is valid (for example, a PR containing only deleted files).
    if (-not (Test-Path $PackageInfoDirectory -PathType Container)) {
        Write-Host 'No package metadata was produced for this PR.'
        return
    }

    $packages = @(
        Get-ChildItem $PackageInfoDirectory -Filter '*.json' -File -Recurse |
            ForEach-Object { Get-Content $_.FullName -Raw | ConvertFrom-Json } |
            Where-Object { $_.IncludedForValidation -eq $false -and $_.Name -like 'Azure.ResourceManager.*' } |
            Sort-Object DirectoryPath -Unique
    )
    $failedPackages = @()
    $changelogPaths = @()
    foreach ($package in $packages) {
        try {
            $batchPackagePath = [IO.Path]::GetFullPath((Join-Path $sdkRepoPath $package.DirectoryPath))
            $relativePath = [IO.Path]::GetRelativePath($sdkRepoPath, $batchPackagePath).Replace('\', '/')
            if ($relativePath -notmatch '^sdk/[^/]+/Azure\.ResourceManager\.[^/]+$' -or
                $relativePath.Split('/') -contains '..' -or
                (Split-Path $batchPackagePath -Leaf) -ne $package.Name) {
                throw "Unexpected management package directory '$($package.DirectoryPath)'."
            }

            $changelogPath = "$relativePath/CHANGELOG.md"
            $changelogPaths += $changelogPath
            Write-Host "Generating changelog for $($package.Name)."
            # Use only the single-package parameter set: never recurse into batch mode.
            & pwsh -NoProfile -File $PSCommandPath `
                -PackagePath $batchPackagePath -SdkRepoPath $sdkRepoPath
            if ($LASTEXITCODE -ne 0) {
                $failedPackages += $package.Name
            }

            if (Test-Path (Join-Path $sdkRepoPath $changelogPath) -PathType Leaf) {
                $destination = Join-Path $outputDirectory $changelogPath
                New-Item -ItemType Directory -Path (Split-Path $destination -Parent) -Force | Out-Null
                Copy-Item (Join-Path $sdkRepoPath $changelogPath) $destination
            }
        }
        catch {
            $failedPackages += $package.Name
            Write-Warning "Failed to update '$($package.Name)': $_"
        }
    }

    if ($changelogPaths.Count -gt 0) {
        $patchPath = Join-Path $outputDirectory 'changelog.patch'
        & git -C $sdkRepoPath diff --binary "--output=$patchPath" -- @changelogPaths
        if ($LASTEXITCODE -ne 0) {
            throw 'Failed to export the generated changelog patch.'
        }
    }
    else {
        Write-Host 'No directly changed management packages require changelog generation.'
    }

    if ($failedPackages.Count -gt 0) {
        throw "Changelog generation failed for: $($failedPackages -join ', ')."
    }
    return
}

try {
    $packagePath = (Resolve-Path $PackagePath).Path
    $sdkRepoPath = (Resolve-Path $SdkRepoPath).Path
    $relativePackagePath = [IO.Path]::GetRelativePath($sdkRepoPath, $packagePath)
    if ([IO.Path]::IsPathRooted($relativePackagePath) -or $relativePackagePath -eq ".." -or $relativePackagePath.StartsWith("..$([IO.Path]::DirectorySeparatorChar)")) {
        throw "Package path '$packagePath' is not under SDK repository '$sdkRepoPath'."
    }

    $projectFiles = @(Get-ChildItem -Path (Join-Path $packagePath "src") -Filter "*.csproj" -File)
    if ($projectFiles.Count -ne 1) {
        throw "Expected one project under '$packagePath/src', found $($projectFiles.Count)."
    }

    [xml]$project = Get-Content $projectFiles[0].FullName
    $packageName = [string]$project.Project.PropertyGroup.PackageId
    if ([string]::IsNullOrWhiteSpace($packageName)) {
        $packageName = $projectFiles[0].BaseName
    }
    if (-not $packageName.StartsWith("Azure.ResourceManager.")) {
        throw "Package '$packageName' is not an Azure Resource Manager package."
    }

    $releaseVersion = [string]$project.Project.PropertyGroup.Version
    if ([string]::IsNullOrWhiteSpace($releaseVersion)) {
        throw "No package version found in '$($projectFiles[0].FullName)'."
    }

    $serviceName = Split-Path (Split-Path $packagePath -Parent) -Leaf
    $releaseDate = [DateTime]::UtcNow.ToString("yyyy-MM-dd")
    $apiFilePath = Join-Path $packagePath "api/$packageName.netstandard2.0.cs"
    if (-not (Test-Path $apiFilePath -PathType Leaf)) {
        throw "API listing '$apiFilePath' was not found."
    }

    Write-Host "Generating changelog for package '$packageName', service '$serviceName', version '$releaseVersion'."
    & (Join-Path $PSScriptRoot "Gen-Mgmt-Changelog.ps1") `
        -ServiceName $serviceName `
        -ReleaseVersion $releaseVersion `
        -ReleaseDate $releaseDate `
        -ApiFilePath $apiFilePath

    if (-not $?) {
        throw "Gen-Mgmt-Changelog.ps1 failed for package '$packageName'."
    }

    Write-Host "CHANGELOG.md updated successfully for '$packageName'."
    exit 0
}
catch {
    Write-Error "Failed to update management package changelog: $_" -ErrorAction Continue
    Write-Error "Stack trace: $($_.ScriptStackTrace)" -ErrorAction Continue
    exit 1
}