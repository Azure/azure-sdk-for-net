#Requires -Version 7.0

<#
.SYNOPSIS
Runs the Windows matrix against a checkout graph generated by the Linux validation container.

.DESCRIPTION
VALIDATION ONLY. Production generates one Linux-hosted graph/map and fans it out to Windows jobs,
so this script deliberately reuses the Linux-generated inputs rather than rebuilding them locally.
#>
[CmdletBinding()]
param(
    [string] $RepoRoot,
    [string] $InputRoot,
    [string] $ResultsRoot,
    [string] $WorktreeRoot,
    [string] $ArtifactFilter = '.*',
    [string] $MatrixFilter = '.*',
    [int] $MaxCases = 0,
    [ValidateSet('Stop', 'Continue')][string] $FailureMode = 'Continue',
    [switch] $Resume,
    [switch] $ListOnly,
    [switch] $SkipRecordings,
    [switch] $SkipAzurite
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'
if (!$IsWindows) { throw 'Invoke-WindowsValidation.ps1 must run on Windows.' }

if (!$RepoRoot) { $RepoRoot = Resolve-Path (Join-Path $PSScriptRoot '../../../..') }
$RepoRoot = [System.IO.Path]::GetFullPath($RepoRoot)
$validationRoot = Join-Path $RepoRoot 'artifacts/validation/RepositoryProjectGraph/sparse-checkout'
if (!$InputRoot) { $InputRoot = Join-Path $validationRoot 'inputs' }
if (!$ResultsRoot) { $ResultsRoot = Join-Path $validationRoot 'runs/windows' }
if (!$WorktreeRoot) { $WorktreeRoot = Join-Path ([System.IO.Path]::GetTempPath()) 'azsdk-sparse-validation-windows' }

if (!$ListOnly) {
    & (Join-Path $PSScriptRoot 'Install-WindowsPrerequisites.ps1') -RepoRoot $RepoRoot -CheckOnly
}

$arguments = @{
    RepoRoot = $RepoRoot
    InputRoot = $InputRoot
    ResultsRoot = $ResultsRoot
    TargetHost = 'Windows'
    WorktreeRoot = $WorktreeRoot
    ArtifactFilter = $ArtifactFilter
    MatrixFilter = $MatrixFilter
    MaxCases = $MaxCases
    FailureMode = $FailureMode
}
if ($Resume) { $arguments.Resume = $true }
if ($ListOnly) { $arguments.ListOnly = $true }
if ($SkipRecordings) { $arguments.SkipRecordings = $true }
if ($SkipAzurite) { $arguments.SkipAzurite = $true }

& (Join-Path $PSScriptRoot 'Invoke-SparseCheckoutValidation.ps1') @arguments
