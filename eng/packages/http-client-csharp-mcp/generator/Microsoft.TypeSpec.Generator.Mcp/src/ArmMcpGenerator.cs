using System.ComponentModel.Composition;
using Azure.Generator.Management;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.TypeSpec.Generator.Providers;
using Microsoft.TypeSpec.Generator.SourceInput;

namespace Microsoft.TypeSpec.Generator.Mcp;

[Export(typeof(CodeModelGenerator))]
[ExportMetadata(GeneratorMetadataName, nameof(ArmMcpGenerator))]
[method: ImportingConstructor]
public sealed class ArmMcpGenerator(GeneratorContext context) : ManagementClientGenerator(context)
{
    private McpManifest? _manifest;
    internal McpManifest Manifest => _manifest ??= McpManifest.Load(Path.Combine(Configuration.OutputDirectory, "tspMcpCodeModel.json"));
    public override ManagementOutputLibrary OutputLibrary { get; } = new ArmMcpOutputLibrary();
    internal IReadOnlyList<MetadataReference> SdkReferences { get; private set; } = [];
    private SourceInputModel? _source;
    public override SourceInputModel SourceInputModel
    {
        get
        {
            var source = base.SourceInputModel;
            // Describe the stock SDK surface, not customization methods from the MCP consumer.
            return _source ??= new SourceInputModel(source.Customization!.RemoveAllSyntaxTrees(), source.LastContract, source.ApiCompatBaseline);
        }
    }

    protected override void Configure()
    {
        base.Configure();
        SdkReferences = ConsumerMetadata.Resolve(Configuration.OutputDirectory, includeSdkAssemblies: true)
            .Select(path => (MetadataReference)MetadataReference.CreateFromFile(path)).ToArray();
        foreach (var reference in SdkReferences)
        {
            AddMetadataReference(reference);
        }
    }

    public override Task WriteAdditionalFiles(string outputPath)
    {
        var library = (ArmMcpOutputLibrary)OutputLibrary;
        foreach (var binding in library.Bindings)
        {
            OptionsSyntaxAdapter.Rewrite(Path.Combine(outputPath, "src", "Generated", binding.Prefix + "Options.cs"), binding.Options);
            var optionPath = Path.Combine(outputPath, "src", "Generated", binding.Prefix + "Options.cs");
            File.WriteAllText(optionPath, ArmOptionsProvider.RewriteSource(File.ReadAllText(optionPath)));
            CommandSyntaxAdapter.RewritePrimary(Path.Combine(outputPath, "src", "Generated", binding.Prefix + "Command.cs"));
        }
        var helper = ReadPageTokenSource();
        File.WriteAllText(Path.Combine(outputPath, "src", "Generated", nameof(ArmToolPageToken) + ".cs"), helper);
        return Task.CompletedTask;
    }

    internal static string ReadPageTokenSource()
    {
        using var stream = typeof(ArmMcpGenerator).Assembly.GetManifestResourceStream(
            "Microsoft.TypeSpec.Generator.Mcp.ArmToolPageToken.cs")
            ?? throw new InvalidOperationException("Missing shared ARM continuation implementation.");
        using var reader = new StreamReader(stream);
        return "// <auto-generated/>\n#nullable enable\n" + reader.ReadToEnd().Replace("\r\n", "\n", StringComparison.Ordinal);
    }
}

internal sealed class ArmMcpOutputLibrary : ManagementOutputLibrary
{
    internal IReadOnlyList<ArmBinding> Bindings { get; private set; } = [];

    protected override TypeProvider[] BuildTypeProviders()
    {
        var stock = base.BuildTypeProviders();
        var generator = (ArmMcpGenerator)CodeModelGenerator.Instance;
        var providers = new List<TypeProvider>();
        var bindings = generator.Manifest.Commands.Select(selection =>
            ArmBinding.Create(selection, stock, generator.SourceInputModel.Customization!)).ToArray();
        foreach (var binding in bindings)
        {
            var manifest = generator.Manifest with { Namespace = binding.Selection.Namespace };
            var options = new ArmOptionsProvider(manifest, binding);
            var result = new ArmResultProvider(manifest, binding);
            var adapter = new ArmSdkAdapterProvider(manifest, binding, options, result);
            var json = new ToolJsonContextProvider(manifest, binding.Prefix + "JsonContext", result, options);
            var command = new ArmCommandProvider(manifest, binding, options, result, adapter, json);
            providers.AddRange([options, result, adapter, json, command, new ArmCatalogProvider(manifest, binding, command)]);
        }
        var trees = providers.Where(provider => provider is ArmSdkAdapterProvider or ArmOptionsProvider or ArmResultProvider)
            .Select(provider =>
            {
                var source = generator.GetWriter(provider).Write().Content;
                if (provider is ArmOptionsProvider)
                {
                    source = ArmOptionsProvider.RewriteSource(OptionsSyntaxAdapter.RewriteSource(source,
                        bindings.Single(binding => provider.Name == binding.Prefix + "Options").Options));
                }
                return CSharpSyntaxTree.ParseText(source, path: provider.RelativeFilePath);
            })
            .Append(CSharpSyntaxTree.ParseText(ArmMcpGenerator.ReadPageTokenSource()));
        var compilation = CSharpCompilation.Create("McpSdkBinding", trees, generator.SdkReferences,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        var errors = compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        McpManifest.Require(errors.Length == 0,
            "Complete ARM SDK adapter binding failed against the referenced package closure:\n" +
            string.Join("\n", errors.Select(error => error.ToString())) +
            "\nUse the matching SDK/provider input or an explicit handwritten operation override.");
        Bindings = bindings;
        return providers.ToArray();
    }
}
