using System.Threading.Tasks;
using NUnit.Framework;
using Verifier = Azure.SdkAnalyzers.Tests.AzureAnalyzerVerifier<Azure.SdkAnalyzers.DataSuffixAnalyzer>;

namespace Azure.SdkAnalyzers.Tests
{
    public class AZC0032Tests
    {
        private const string JsonModelStub = @"namespace System.ClientModel.Primitives
{
    public interface IJsonModel<T> { }
}
";

        private const string ResourceDataStub = @"namespace Azure.ResourceManager.Models
{
    public class ResourceData { }

    public class TrackedResourceData : ResourceData { }
}
";

        private const string JsonElementStub = @"namespace System.Text.Json
{
    public struct JsonElement { }
}
";

        // A modern generated model serializes through IJsonModel<T> and lives outside a Models
        // namespace, so none of the legacy recognition paths see it.
        [Test]
        public async Task AZC0032ProducedForJsonModelOutsideModelsNamespace()
        {
            const string code = JsonModelStub + @"
namespace Azure.Fake.Widgets
{
    public class {|AZC0032:WidgetData|} : System.ClientModel.Primitives.IJsonModel<WidgetData> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032ProducedForJsonModelInheritedThroughAnotherInterface()
        {
            const string code = JsonModelStub + @"
namespace Azure.Fake.Widgets
{
    public interface IWidgetModel<T> : System.ClientModel.Primitives.IJsonModel<T> { }

    public class {|AZC0032:WidgetData|} : IWidgetModel<WidgetData> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032ProducedForJsonModelInheritedFromBaseModel()
        {
            const string code = JsonModelStub + @"
namespace Azure.Fake.Widgets
{
    public class WidgetBase : System.ClientModel.Primitives.IJsonModel<WidgetBase> { }

    public class {|AZC0032:WidgetData|} : WidgetBase { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032ProducedForJsonModelInGeneratedCode()
        {
            const string code = @"// <auto-generated/>
" + JsonModelStub + @"
namespace Azure.Fake.Widgets
{
    public class {|AZC0032:WidgetData|} : System.ClientModel.Primitives.IJsonModel<WidgetData> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032ProducedForModelInModelsNamespace()
        {
            const string code = @"
namespace Azure.Fake.Widgets.Models
{
    public class {|AZC0032:WidgetData|} { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032ProducedForUtf8JsonSerializableModel()
        {
            const string code = @"namespace Azure.Core
{
    public interface IUtf8JsonSerializable { }
}

namespace Azure.Fake.Widgets
{
    public class {|AZC0032:WidgetData|} : Azure.Core.IUtf8JsonSerializable { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032ProducedForModelWithJsonElementDeserializer()
        {
            const string code = JsonElementStub + @"
namespace Azure.Fake.Widgets
{
    public class {|AZC0032:WidgetData|}
    {
        public static WidgetData DeserializeWidgetData(System.Text.Json.JsonElement element) => null;
    }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032NotProducedForResourceData()
        {
            const string code = JsonModelStub + ResourceDataStub + @"
namespace Azure.Fake.Widgets
{
    public class WidgetData : Azure.ResourceManager.Models.ResourceData, System.ClientModel.Primitives.IJsonModel<WidgetData> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032NotProducedForTrackedResourceData()
        {
            const string code = JsonModelStub + ResourceDataStub + @"
namespace Azure.Fake.Widgets
{
    public class WidgetData : Azure.ResourceManager.Models.TrackedResourceData, System.ClientModel.Primitives.IJsonModel<WidgetData> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032NotProducedForIndirectResourceDataInheritance()
        {
            const string code = JsonModelStub + ResourceDataStub + @"
namespace Azure.Fake.Widgets
{
    public class WidgetBaseData : Azure.ResourceManager.Models.ResourceData, System.ClientModel.Primitives.IJsonModel<WidgetBaseData> { }

    public class WidgetData : WidgetBaseData { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        // A ResourceData lookalike from another namespace is not the Azure.ResourceManager type
        // the exemption is scoped to.
        [Test]
        public async Task AZC0032ProducedForResourceDataLookalikeBaseType()
        {
            const string code = JsonModelStub + @"
namespace Contoso.Models
{
    public class ResourceData { }
}

namespace Azure.Fake.Widgets
{
    public class {|AZC0032:WidgetData|} : Contoso.Models.ResourceData, System.ClientModel.Primitives.IJsonModel<WidgetData> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032NotProducedForJsonModelLookalikeInterface()
        {
            const string code = @"
namespace Contoso.Serialization
{
    public interface IJsonModel<T> { }
}

namespace Azure.Fake.Widgets
{
    public class WidgetData : Contoso.Serialization.IJsonModel<WidgetData> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032NotProducedForNonModelType()
        {
            const string code = @"
namespace Azure.Fake.Widgets
{
    public class WidgetData
    {
        public string Name { get; set; }
    }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032NotProducedForNonPublicModel()
        {
            const string code = @"
namespace Azure.Fake.Widgets.Models
{
    internal class WidgetData { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032NotProducedForModelWithoutDataSuffix()
        {
            const string code = JsonModelStub + @"
namespace Azure.Fake.Widgets
{
    public class WidgetInfo : System.ClientModel.Primitives.IJsonModel<WidgetInfo> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }

        [Test]
        public async Task AZC0032NotProducedOutsideSdkCode()
        {
            const string code = JsonModelStub + @"
namespace Contoso.Widgets
{
    public class WidgetData : System.ClientModel.Primitives.IJsonModel<WidgetData> { }
}";

            await Verifier.VerifyAnalyzerAsync(code);
        }
    }
}
