        // Custom: the generated parameterless constructor has no base type constructor to call.
        /// <summary> Initializes a new instance of <see cref="OutputItemCustomToolCallOutput"/> for deserialization. </summary>
        internal OutputItemCustomToolCallOutput() : base("custom_tool_call_output")
        {
        }

        // Custom: ResponseItem already declares Id and writes it, so a generated Id would hide it (and
        // ResponseItem.Id would read null) and write id twice. This replaces the generated property: the
        // setter stores into the base Id and the getter returns null so that only the base type writes id.
        [CodeGenMember("Id")]
        internal string IdInternal
        {
            get => null;
            set => Id = value;
        }

        // Custom: created_by, agent_reference and response_id live in the JsonPatch of ResponseItem (see
        // ResponseItemAttributionExtensions) because the base type has no properties for them. Mapping
        // them back to the generated model makes the generated serializer write each of them exactly once.
        [CodeGenMember("CreatedBy")]
        internal BinaryData CreatedByInternal => this.CreatedBy;

        [CodeGenMember("AgentReference")]
        internal AgentReference AgentReferenceInternal => this.AgentReference;

        [CodeGenMember("ResponseId")]
        internal string ResponseIdInternal => this.ResponseId;

        // Custom: AgentReference.DeserializeAgentReference is internal to Azure.AI.Extensions.OpenAI, so the
        // call the generator emits for agent_reference cannot compile in this assembly. Read it through the
        // model context instead, as the generated code does for the other AgentReference properties.
        private static void DeserializeAgentReferenceValue(JsonProperty property, ref AgentReference agentReference, ModelReaderWriterOptions options)
        {
            if (property.Value.ValueKind == JsonValueKind.Null)
            {
                return;
            }

            agentReference = ModelReaderWriter.Read<AgentReference>(property.Value.GetUtf8Bytes(), options, AzureAIAgentServerResponsesContext.Default);
        }
    }
