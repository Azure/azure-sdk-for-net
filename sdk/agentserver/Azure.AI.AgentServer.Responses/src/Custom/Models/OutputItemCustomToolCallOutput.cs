    [CodeGenSuppress(nameof(OutputItemCustomToolCallOutput), typeof(ResponseItemKind), typeof(BinaryData), typeof(AgentReference), typeof(string), typeof(string), typeof(string), typeof(ToolCallCallerParam), typeof(BinaryData), typeof(FunctionCallOutputStatusEnum), typeof(BinaryData), typeof(IDictionary<string, BinaryData>))]
