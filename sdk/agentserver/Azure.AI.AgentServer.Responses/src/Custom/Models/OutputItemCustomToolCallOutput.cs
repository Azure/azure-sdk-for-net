    public partial class OutputItemCustomToolCallOutput
    {
        // Custom: replaces the generated constructor so that it calls base(@type) and stores the values the
        // ResponseItem base type has no constructor for.
        /// <summary> Initializes a new instance of <see cref="OutputItemCustomToolCallOutput"/>. </summary>
        /// <param name="type"></param>
        /// <param name="createdBy"> The information about the creator of the item. </param>
        /// <param name="agentReference"> The agent that created the item. </param>
        /// <param name="responseId"> The response on which the item is created. </param>
