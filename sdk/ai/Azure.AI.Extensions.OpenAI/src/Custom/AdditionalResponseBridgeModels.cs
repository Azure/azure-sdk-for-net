using System.Collections.Generic;
using System.Linq;
using OpenAI.Responses;

namespace Azure.AI.Extensions.OpenAI;

/// <summary> Local shell call. </summary>
public class OutputItemLocalShellToolCall : ResponseItem
{
    /// <summary> Initializes a new instance of <see cref="OutputItemLocalShellToolCall"/>. </summary>
    public OutputItemLocalShellToolCall(string id, string callId, LocalShellExecAction action, ItemLocalShellToolCallStatus status)
        : base(ResponseItemKind.LocalShellCall)
    {
        Id = id;
        CallId = callId;
        Action = action;
        Status = status;
    }

    /// <summary> The unique ID of the local shell call. </summary>
    public new string Id { get; set; }

    /// <summary> The unique ID of the local shell tool call generated by the model. </summary>
    public string CallId { get; }

    /// <summary> Gets the action. </summary>
    public LocalShellExecAction Action { get; }

    /// <summary> The status of the local shell call. </summary>
    public ItemLocalShellToolCallStatus Status { get; }
}

/// <summary> Local shell call output. </summary>
public partial class OutputItemLocalShellToolCallOutput : ResponseItem
{
    /// <summary> Initializes a new instance of <see cref="OutputItemLocalShellToolCallOutput"/>. </summary>
    public OutputItemLocalShellToolCallOutput(string id, string output)
        : base(ResponseItemKind.LocalShellCallOutput)
    {
        Id = id;
        Output = output;
    }

    /// <summary> The unique ID of the local shell call output. </summary>
    public new string Id { get; set; }

    /// <summary> A JSON string of the output of the local shell tool call. </summary>
    public string Output { get; }

    /// <summary> Gets or sets the status. </summary>
    public ItemLocalShellToolCallOutputStatus? Status { get; set; }
}

/// <summary> Compaction item. </summary>
public class OutputItemCompactionBody : ResponseItem
{
    /// <summary> Initializes a new instance of <see cref="OutputItemCompactionBody"/>. </summary>
    public OutputItemCompactionBody(string id, string encryptedContent)
        : base(ResponseItemKind.Compaction)
    {
        Id = id;
        EncryptedContent = encryptedContent;
    }

    /// <summary> The unique ID of the compaction item. </summary>
    public new string Id { get; set; }

    /// <summary> The encrypted content that was produced by compaction. </summary>
    public string EncryptedContent { get; }
}

/// <summary> Local shell exec action. </summary>
public partial class LocalShellExecAction
{
    /// <summary> Initializes a new instance of <see cref="LocalShellExecAction"/>. </summary>
    public LocalShellExecAction(IEnumerable<string> command, IDictionary<string, string> env = null)
    {
        Command = command.ToList();
        Env = env;
    }

    /// <summary> The type of the local shell action. Always <c>exec</c>. </summary>
    public string Type { get; } = "exec";

    /// <summary> The command to run. </summary>
    public IList<string> Command { get; }

    /// <summary> Gets the timeout, in milliseconds. </summary>
    public long? TimeoutMs { get; set; }

    /// <summary> Gets the working directory. </summary>
    public string WorkingDirectory { get; set; }

    /// <summary> Environment variables to set for the command. </summary>
    public IDictionary<string, string> Env { get; }

    /// <summary> Gets the user. </summary>
    public string User { get; set; }
}

/// <summary> Local shell call status. </summary>
public enum ItemLocalShellToolCallStatus
{
    /// <summary> The local shell call is in progress. </summary>
    InProgress,
    /// <summary> The local shell call is completed. </summary>
    Completed,
    /// <summary> The local shell call is incomplete. </summary>
    Incomplete
}

/// <summary> Local shell call output status. </summary>
public enum ItemLocalShellToolCallOutputStatus
{
    /// <summary> The local shell call output is in progress. </summary>
    InProgress,
    /// <summary> The local shell call output is completed. </summary>
    Completed,
    /// <summary> The local shell call output is incomplete. </summary>
    Incomplete
}

